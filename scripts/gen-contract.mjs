#!/usr/bin/env node
/**
 * Generate lib/generated/contract.ts and docs/reference/contract.md from
 * mace-api/contract.json.
 *
 * The JSON is the single source of truth for what the backend accepts (it is
 * enforced in mace-api/contract.py). A plain JSON import would widen every
 * literal to `string`; generating an `as const` module keeps model ids, sizes
 * and calculation types as literal types, so the compiler catches a UI option
 * the backend would refuse.
 *
 *   node scripts/gen-contract.mjs          # write
 *   node scripts/gen-contract.mjs --check  # exit 1 if the file is stale (CI)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "mace-api", "contract.json");
const target = join(root, "lib", "generated", "contract.ts");

const contract = JSON.parse(readFileSync(source, "utf8"));
delete contract.$comment;

const output =
  "// GENERATED by scripts/gen-contract.mjs from mace-api/contract.json — do not edit.\n" +
  "// Run `npm run gen:contract` after changing the JSON.\n\n" +
  `export const CONTRACT = ${JSON.stringify(contract, null, 2)} as const;\n\n` +
  "export type Contract = typeof CONTRACT;\n";

/** docs/reference/contract.md — the human-readable view of the same file. */
function renderDocs(c) {
  const row = (cells) => `| ${cells.join(" | ")} |`;
  const lines = [
    "<!-- GENERATED by scripts/gen-contract.mjs from mace-api/contract.json — do not edit. -->",
    "",
    "# Request contract",
    "",
    `What the backend accepts, as enforced by \`mace-api/contract.py\` (contract v${c.contractVersion}, app v${c.appVersion}).`,
    "The UI and the Next.js routes read the same file, so this page, the code and the",
    "interface cannot disagree. Decisions: [ADR-0021](../adr/0021-model-registry-mpa0-default.md),",
    "[ADR-0022](../adr/0022-shared-request-contract.md).",
    "",
    "## Calculation types",
    "",
    `Supported: ${c.calculationTypes.map((t) => `\`${t}\``).join(", ")}. Refused with an explanation: ${Object.keys(c.refusedCalculationTypes).map((t) => `\`${t}\``).join(", ")}.`,
    `MD ensembles: ${c.mdEnsembles.join(", ")} (NPT requires a fully periodic cell). Precisions: ${c.precisions.join(", ")}. Devices: ${c.devices.join(", ")}.`,
    `Structure files: ${c.structureExtensions.map((e) => `\`${e}\``).join(", ")}, or a bare \`POSCAR\`/\`CONTCAR\`.`,
    "",
    "## Parameters",
    "",
    row(["Parameter", "Type", "Default", "Range", "Unit"]),
    row(["---", "---", "---", "---", "---"]),
    ...Object.entries(c.params).map(([k, v]) => row([`\`${k}\``, v.type, String(v.default), `${v.min} – ${v.max}`, v.unit || "—"])),
    "",
    "Every number must be finite; booleans are not numbers; step counts must be whole.",
    "",
    "## Deployment profiles",
    "",
    "`SIMPLEATOM_PROFILE` selects one; the hosted Space runs `hosted`, a local checkout `local`.",
    "",
    row(["Limit", ...Object.keys(c.profiles)]),
    row(["---", ...Object.keys(c.profiles).map(() => "---")]),
  ];
  const profiles = Object.values(c.profiles);
  const flat = (p) => {
    const out = {};
    for (const [k, v] of Object.entries(p)) {
      if (k === "description") continue;
      if (v && typeof v === "object") for (const [k2, v2] of Object.entries(v)) out[`${k} (${k2})`] = v2;
      else out[k] = v;
    }
    return out;
  };
  const flats = profiles.map(flat);
  for (const key of Object.keys(flats[0])) {
    lines.push(row([`\`${key}\``, ...flats.map((f) => (typeof f[key] === "number" ? f[key].toLocaleString("en-US") : String(f[key])))]));
  }
  lines.push(
    "",
    "## Models",
    "",
    `Default when \`modelType\` is omitted: **${c.defaultModelType}**.`,
    "",
    row(["Model", "Domain", "Sizes", "Level of theory", "Licence", "Hosted"]),
    row(["---", "---", "---", "---", "---", "---"]),
    ...c.models.map((m) =>
      row([
        `\`${m.id}\`${m.aliases.length ? ` (alias ${m.aliases.map((a) => `\`${a}\``).join(", ")})` : ""}`,
        m.domain,
        Object.keys(m.sizes).join(", ") || "—",
        m.levelOfTheory ?? "—",
        m.license.id ?? "your own",
        m.hostedEnabled ? "yes" : "no",
      ]),
    ),
    "",
    "Every foundation checkpoint is pinned by SHA-256; a file that does not match its pin is refused",
    "before it is unpickled ([ADR-0020](../adr/0020-trusted-checkpoint-loading.md)).",
    "",
    "## Energy conventions",
    "",
    row(["Convention", "Description", "Enforced by the validator (eV/atom)", "Typical (eV/atom)"]),
    row(["---", "---", "---", "---"]),
    ...Object.entries(c.energyConventions).map(([k, v]) =>
      row([
        `\`${k}\``,
        v.description,
        v.enforced ? `${v.enforced.minEvPerAtom} to ${v.enforced.maxEvPerAtom}` : "skipped",
        v.typical ? `${v.typical.minEvPerAtom} to ${v.typical.maxEvPerAtom}` : "—",
      ]),
    ),
    "",
    "The enforced band is what the advisory validator checks: below the minimum is a warning,",
    "above the maximum an issue. The typical band is for orientation only.",
    "",
  );
  return lines.join("\n");
}

const docsTarget = join(root, "docs", "reference", "contract.md");
const docsOutput = renderDocs(contract);

if (process.argv.includes("--check")) {
  const stale = [];
  if ((existsSync(target) ? readFileSync(target, "utf8") : "") !== output) stale.push("lib/generated/contract.ts");
  if ((existsSync(docsTarget) ? readFileSync(docsTarget, "utf8") : "") !== docsOutput) stale.push("docs/reference/contract.md");
  if (stale.length) {
    console.error(`${stale.join(" and ")} stale. Run \`npm run gen:contract\`.`);
    process.exit(1);
  }
  console.log("lib/generated/contract.ts and docs/reference/contract.md are up to date.");
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
  mkdirSync(dirname(docsTarget), { recursive: true });
  writeFileSync(docsTarget, docsOutput);
  console.log(`wrote ${target}\nwrote ${docsTarget}`);
}
